package com.fu.conversation.entity;

import com.fu.course.entity.Course;
import com.fu.infrastructure.persistence.BaseEntity;
import jakarta.persistence.*;
import lombok.*;
import lombok.experimental.SuperBuilder;
import org.hibernate.annotations.ColumnTransformer;

import java.util.UUID;

/**
 * UserConversationTopic - Chủ đề hội thoại do học sinh tự tạo (private).
 * Learner inputs a title/scenario; AI generates vocabulary hints and grammar context.
 * Optionally linked to a course for richer context.
 * Maps to speaking.user_conversation_topics table.
 */
@Entity
@Table(name = "user_conversation_topics", schema = "speaking",
        indexes = {
                @Index(name = "idx_user_topics_user", columnList = "user_id"),
                @Index(name = "idx_user_topics_course", columnList = "course_id")
        })
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@SuperBuilder
@ToString(callSuper = true)
public class UserConversationTopic extends BaseEntity {

    @Column(name = "user_id", nullable = false)
    private UUID userId;

    @Column(name = "title", nullable = false, length = 255)
    private String title;

    /**
     * Free-form scenario description entered by the learner.
     * Used as input for AI context generation.
     */
    @Column(name = "scenario", columnDefinition = "TEXT")
    private String scenario;

    @Enumerated(EnumType.STRING)
    @Column(name = "jlpt_level", length = 5)
    @ColumnTransformer(write = "CAST(? AS jlpt_level)")
    private Course.JlptLevel jlptLevel;

    /**
     * Optional course for richer vocabulary/grammar context.
     */
    @Column(name = "course_id")
    private UUID courseId;

    /**
     * AI-generated context: vocabularyHints, grammarPoints, usefulExpressions.
     * Generated by ConversationGenerationService based on scenario + courseId.
     */
    @Column(name = "ai_generated_context", columnDefinition = "jsonb")
    @Builder.Default
    private String aiGeneratedContext = "{}";

    @Enumerated(EnumType.STRING)
    @Column(name = "status", columnDefinition = "content_status")
    @ColumnTransformer(write = "CAST(? AS content_status)")
    @Builder.Default
    private Course.ContentStatus status = Course.ContentStatus.DRAFT;
}
