package com.fu.curriculumimport.service.agent;

import com.fu.curriculumimport.service.ingestion.DocumentChunk;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.util.List;
import java.util.Map;

/**
 * Holds the AI extraction result from a single chunk.
 */
@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class ExtractionResult {

    private int chunkIndex;
    private double confidence;
    private int tokensUsed;
    private long processingTimeMs;

    /**
     * Lesson number detected from the source chunk (e.g. 1 for "Bài 1").
     * Null when lesson-aware chunking was not used.
     */
    private Integer lessonNumber;

    /**
     * Lesson title detected from the source chunk (e.g. "Bài 1").
     * Null when lesson-aware chunking was not used.
     */
    private String lessonTitle;

    private List<ExtractedLesson> lessons;
    private List<ExtractedVocabulary> vocabulary;
    private List<ExtractedGrammar> grammarPoints;

    @Data
    @Builder
    @NoArgsConstructor
    @AllArgsConstructor
    public static class ExtractedLesson {
        private String title;
        private String titleJapanese;
        private String description;
        private String lessonType; // VOCABULARY, GRAMMAR, KANJI, MIXED
        private String content; // JSON string
        private List<String> objectives;
        private int pageStart;
        private int pageEnd;
        private int orderIndex;
    }

    @Data
    @Builder
    @NoArgsConstructor
    @AllArgsConstructor
    public static class ExtractedVocabulary {
        private String japaneseText;
        private String reading;
        private String romaji;
        private String meaningVi;
        private String meaningEn;
        private String partOfSpeech;
        private String jlptLevel;
        private String kanjiWriting;
        private List<Map<String, String>> exampleSentences;
        private boolean isKeyWord;
        /**
         * Origin of the Vietnamese/English meanings.
         * <ul>
         *   <li>{@code "SOURCE"} — meaning was explicitly present in the source document.</li>
         *   <li>{@code "AI_INFERRED"} — meaning was generated by the AI from context
         *       (e.g. PPTX slide only lists Japanese words without translations).</li>
         * </ul>
         * Frontend should highlight AI_INFERRED items for manager review.
         */
        private String meaningSource; // "SOURCE" | "AI_INFERRED"
    }

    @Data
    @Builder
    @NoArgsConstructor
    @AllArgsConstructor
    public static class ExtractedGrammar {
        private String pattern;
        private String patternReading;
        private String meaningVi;
        private String meaningEn;
        private String shortExplanation;
        private String detailedExplanation;
        private String jlptLevel;
        private String category;
        private List<Map<String, String>> exampleSentences;
        private List<Map<String, String>> commonMistakes;
        private boolean isKeyPoint;
    }
}
